#  Requête 1 — Total des ventes par catégorie et par année
cursor.execute("""
    SELECT
        d.order_year,
        p.categorie,
        ROUND(SUM(f.montant_ventes), 2) AS total_ventes,
        ROUND(SUM(f.profit), 2)         AS total_profit
    FROM FACT_VENTES f
    JOIN DIM_DATE    d ON f.id_date    = d.id_date
    JOIN DIM_PRODUIT p ON f.id_produit = p.id_produit
    GROUP BY d.order_year, p.categorie
    ORDER BY d.order_year, total_ventes DESC
""")
results = cursor.fetchall()
print("\n📊 Requête 1 — Total des ventes par catégorie et par année :")
for row in results:
    print(row)

#  Requête 2 — Top 5 régions par chiffre d'affaires
#It groups sales by region, calculates totals, and returns the top 5 highest-performing regions
cursor.execute("""
    SELECT
        g.region,
        ROUND(SUM(f.montant_ventes), 2) AS total_ventes,
        ROUND(SUM(f.profit), 2)         AS total_profit,
        COUNT(DISTINCT f.id_vente)       AS nb_commandes
    FROM FACT_VENTES f
    JOIN DIM_GEOGRAPHIE g ON f.id_geo = g.id_geo
    GROUP BY g.region
    ORDER BY total_ventes DESC
    LIMIT 5
""")#Connects each sale to its region.
results = cursor.fetchall()
